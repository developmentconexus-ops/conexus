type Invocation = Extract<MastraMessagePart, { type: 'tool-invocation' }>['toolInvocation']

function invocationsOf(parts: readonly MastraMessagePart[]): Invocation[] {
  return parts.flatMap((part) => (part.type === 'tool-invocation' ? [part.toolInvocation] : []))
}

/** Mastra's own rule for a tool that failed (`checks.noToolErrors`), and a refusal: a result whose `kind` is not `OK`. */
function failed(call: Invocation): boolean {
  return (
    call.state === 'call' ||
    call.state === 'output-error' ||
    call.isError === true ||
    Boolean(Object(call.result).error) ||
    (Object(call.result).kind !== undefined && Object(call.result).kind !== 'OK')
  )
}

/** The scorecard of one question's turn: its answer's parts and the events of its turn. */
export function scoreOf(turn: {
  question: number
  parts: readonly MastraMessagePart[]
  events: readonly StreamEvent[]
  right: boolean
}): Scorecard {
  const calls = invocationsOf(turn.parts)
  const seen = new Map<string, number>()
  for (const call of calls) {
    const key = `${call.toolName} ${JSON.stringify(call.args)}`
    seen.set(key, (seen.get(key) ?? 0) + 1)
  }
  const helperCalls = turn.events.filter((event) => event.type === 'subagent_tool_start').length
  const first = turn.events.find((event) => event.type === 'usage_update')
  return {
    question: turn.question,
    right: turn.right,
    calls: calls.length + helperCalls,
    errors: calls.filter(failed).length,
    repeated: [...seen.values()].filter((times) => times > 1).length,
    firstStepTokens: first?.type === 'usage_update' ? first.usage.promptTokens : undefined,
    helpers: turn.events.filter((event) => event.type === 'subagent_end').length,
  }
}

/**
 * Whether the answer is right for the question, by its column "Certo quando": what it says, that it
 * read nothing when it must not, and what the doubles' own data makes the right answer
 * (`test-truths.ts`).
 */
export function judged(asked: Question, parts: readonly MastraMessagePart[], read: string): boolean {
  const text = textOf([...parts])
  const readOnce = invocationsOf(parts).some(
    (call) =>
      call.toolName === read ||
      call.toolName.startsWith('sankhya_') ||
      call.toolName.startsWith('mercado-livre_'),
  )
  if (asked.noRead === true && readOnce) return false
  if (!(asked.says ?? []).every((says) => says.test(text))) return false
  const expected = expectedOf(asked.n)
  return expected === undefined || meets(text, expected)
}
