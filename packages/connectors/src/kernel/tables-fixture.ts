/** A table as every discovery shows it: the suggested name, the source, the key, the mode, whether the start date limits it, and how many columns the double's dictionary or the declaration gives (null: the dictionary does not have the table). */
export type ExpectedTable = Readonly<{
  name: string
  source: string
  key: readonly string[]
  mode: string // 'FULL', 'CHANGED <column>[ registry]' or 'WINDOW <column> <reread>'
  limited: boolean
  columns: number | null
}>

function row(
  name: string,
  source: string,
  key: readonly string[],
  mode: string,
  limited: boolean,
  columns: number | null,
): ExpectedTable {
  return { name, source, key, mode, limited, columns }
}

