/**
 * What one question cost the Assistant, counted from its turn (card U11). `errors` counts every
 * refusal of a read too, and most refusals of the Sankhya questions come from the double, not from
 * the Assistant: its SQLite does not run the Oracle SQL (`TO_CHAR`, `EXTRACT`, `FROM DUAL`) that the
 * real Sankhya accepts. `helpers` counts the helpers that ended, as the turn's log line does.
 */
export type Scorecard = {
  question: number
  right: boolean
  calls: number
  errors: number
  repeated: number
  firstStepTokens: number | undefined
  helpers: number
}

/**
 * The data a question runs on: **SV** the Sankhya sales of September, **SC** the Sankhya register,
 * **ML** the Mercado Livre double, **AQ** the test attachments, **PL** a goals sheet generated by
 * the test, **WEB** none (the provider's search), **none** a conversation with no data.
 */
export type Data = 'SV' | 'SC' | 'ML' | 'AQ' | 'PL' | 'WEB' | 'none'

/** The unit whose work a question waits for: `now` runs today. */
export type Enters = 'now' | 'U7' | 'U9'

export type Question = {
  n: number
  text: string
  data: Data[]
  /** The "Certo quando" column, as the founder approved it. */
  right: string
  enters: Enters
  /** A conversation with no connection chosen. */
  bare?: true
  /** What the answer must say, besides every figure coming from a read. */
  says?: RegExp[]
  /** The turn must not read a connection. */
  noRead?: true
}

function q(
  n: number,
  text: string,
  data: Data[],
  right: string,
  more: Partial<Question> = {},
): Question {
  return { n, text, data, right, enters: 'now', ...more }
}

